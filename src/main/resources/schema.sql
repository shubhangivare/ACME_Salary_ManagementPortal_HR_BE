CREATE TABLE IF NOT EXISTS employees (
 id VARCHAR(30) PRIMARY KEY, name VARCHAR(120) NOT NULL, email VARCHAR(180) NOT NULL UNIQUE,
 department VARCHAR(100) NOT NULL, designation VARCHAR(120) NOT NULL, country VARCHAR(100) NOT NULL,
 currency VARCHAR(3) NOT NULL, salary DECIMAL(15,2) NOT NULL, status VARCHAR(12) NOT NULL,
 joined DATE NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS audit_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, event_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 username VARCHAR(100) NOT NULL, action VARCHAR(80) NOT NULL, detail VARCHAR(1000) NOT NULL
);
CREATE TABLE IF NOT EXISTS salary_revisions (
 id VARCHAR(40) PRIMARY KEY, employee_id VARCHAR(30) NOT NULL, old_salary DECIMAL(15,2) NOT NULL,
 new_salary DECIMAL(15,2) NOT NULL, currency VARCHAR(3) NOT NULL, effective_date DATE NOT NULL,
 reason VARCHAR(500) NOT NULL, username VARCHAR(100) NOT NULL, event_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS countries (
 code VARCHAR(2) PRIMARY KEY, name VARCHAR(100) NOT NULL, currency VARCHAR(3) NOT NULL,
 symbol VARCHAR(12) NOT NULL, rate_to_inr DECIMAL(12,4) NOT NULL, updated DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS app_roles (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(30) NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS app_users (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username VARCHAR(50) NOT NULL UNIQUE, password_hash VARCHAR(100) NOT NULL, display_name VARCHAR(100) NOT NULL, role_id BIGINT NOT NULL, enabled BOOLEAN NOT NULL DEFAULT TRUE, CONSTRAINT fk_app_users_role FOREIGN KEY(role_id) REFERENCES app_roles(id));
